async function main() {
  console.log('🚀 Starting FridayParts Database Seed & Migration...');

  // Step 1: Clean up old items linked to products
  console.log('🧹 Cleaning up old cart items, order items, stock reservations...');
  await prisma.cartItem.deleteMany({});
  await prisma.stockReservation.deleteMany({});
  await prisma.orderItem.deleteMany({});
  await prisma.productImage.deleteMany({});
  
  // Step 2: Delete old products
  console.log('🗑️ Deleting all old products...');
  const deletedProducts = await prisma.product.deleteMany({});
  console.log(`Deleted ${deletedProducts.count} old products.`);

  // Step 3: Upsert the 7 FridayParts Categories
  console.log('📂 Seeding 7 FridayParts Core Categories...');
  for (const cat of CATEGORIES) {
    await prisma.category.upsert({
      where: { slug: cat.slug },
      update: {
        name: cat.name,
        description: cat.description,
        imageUrl: cat.imageUrl,
        order: cat.order,
      },
      create: {
        id: cat.id,
        name: cat.name,
        slug: cat.slug,
        description: cat.description,
        imageUrl: cat.imageUrl,
        order: cat.order,
      },
    });
  }

  // Step 4: Insert the 20 real FridayParts Products
  console.log('⚙️ Inserting 20 authentic FridayParts products...');
  for (const p of FRIDAYPARTS_PRODUCTS) {
    const cat = await prisma.category.findUnique({ where: { slug: p.categoryId.replace('cat-', '') } });
    const createdProduct = await prisma.product.create({
      data: {
        id: p.id,
        title: p.title,
        slug: p.slug,
        sku: p.sku,
        description: p.description,
        shortDescription: p.shortDescription,
        price: p.price,
        compareAtPrice: p.compareAtPrice,
        costPrice: p.costPrice,
        stock: p.stock,
        reservedStock: 0,
        lowStockAlert: 5,
        trackQuantity: true,
        status: 'ACTIVE',
        isFeatured: p.isFeatured,
        categoryId: cat?.id || null,
        brand: p.brand,
        equipmentType: p.equipmentType,
        engineBrand: p.engineBrand,
        weightKg: p.weightKg,
        attributes: p.attributes,
        images: {
          create: p.images.map((url, idx) => ({
            url,
            altText: p.title,
            sortOrder: idx,
            isPrimary: idx === 0,
          })),
        },
      },
    });
    console.log(` + [${createdProduct.sku}] ${createdProduct.title.slice(0, 50)}...`);
  }

  console.log('✅ Successfully seeded 20 FridayParts products and 7 core categories into PostgreSQL!');
}

main()
  .catch((e) => {
    console.error('❌ Seeding error:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
